# počítadlo od 1 do 10
pocitadlo = 1     #inicializace
while pocitadlo <= 10:
    print(f"{pocitadlo}.")
    pocitadlo += 1
pocitadlo = 1  
while pocitadlo > 0:          #podmínka, která je splněna, dokud je proměnná větší než 0
    print(f"{pocitadlo}.")
    pocitadlo -= 1            # změna proměnné, aby se cyklus ukončil